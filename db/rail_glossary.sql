-- rail_glossary.sql — small neutral reference of correct railway terms / column
-- meanings, from the 15.06.2026 РЖД meeting memo (§1.1 terminology, §3.2.2 column
-- glossary). Plain term -> meaning facts; the model reads them as reference, the
-- same way it reads road_codes / delay_reason_codes. Idempotent, additive.

CREATE TABLE IF NOT EXISTS rail_glossary (
    term      text PRIMARY KEY,   -- корректный термин
    meaning   text NOT NULL       -- значение / пояснение
);
