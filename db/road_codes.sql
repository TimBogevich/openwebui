-- road_codes — dictionary mapping every road-code/name variant used across the
-- spravki tables to ONE canonical road name (the full form used by metrics).
-- Mirrors dept_codes (code -> name). NON-DESTRUCTIVE: spravki data is left as-is;
-- the agent JOINs to this dictionary to resolve any spelling.
--
-- Why a dictionary, not a data rewrite: the same road appears as ДВОСТ / ДВС /
-- Дальневосточная depending on the table; rewriting 300+ rows across 5 tables is
-- destructive and easy to get wrong. This is additive and reversible (DROP TABLE).
--
-- Idempotent: re-applies cleanly (TRUNCATE + reinsert).

CREATE TABLE IF NOT EXISTS road_codes (
    code      text PRIMARY KEY,   -- any spelling seen in spravki (code or full name)
    canonical text NOT NULL       -- canonical full road name (= metrics.road form)
);

