-- delay_reason_codes — словарь причин задержки -> нарушение, ответственность,
-- подразделение по Методике ОАО «РЖД» №2040/р от 18.09.2020.
-- Источник истины: пайплайн delay_causes (delay_causes_results.json).
-- Mirrors road_codes/dept_codes. NON-DESTRUCTIVE, additive, dictionary only.
--
-- Ключ = delay_code из spravki_delays (стабильный: 1/21/43…), плюс name для
-- читаемости. Агент делает JOIN spravki_delays.delay_code = drc.delay_code,
-- чтобы ответить «кто ответственен / сколько задержек по чьей вине».
-- Idempotent.

CREATE TABLE IF NOT EXISTS delay_reason_codes (
    delay_code      text PRIMARY KEY,   -- как в spravki_delays.delay_code
    reason_name     text NOT NULL,      -- название причины (как в данных)
    violation       text,              -- нарушение по методике (Раздел III)
    responsibility  text NOT NULL,      -- категория ответственности
    units           text NOT NULL,      -- подразделения-нарушители (через запятую)
    source          text NOT NULL       -- 'методика №2040/р' | 'оценка по аналогии'
);
TRUNCATE delay_reason_codes;
